
/* ==========================================================
   OVERHAUL - products.js
   ----------------------------------------------------------
   商品検索画面

   検索方式：
     ・通常のGET送信（同期検索）
     ・すべての検索条件を検索ボタンで確定
     ・キーワードはEnterキーでも検索可能
     ・検索条件はURLパラメータで管理
     ・ページネーションはPHP側で処理

   JavaScriptによる自動検索は行わない。
   ========================================================== */

(() => {
    "use strict";

    const form = document.getElementById("productSearchForm");

    if (!form) return;

    /*
    |--------------------------------------------------------------------------
    | 検索フォーム送信
    |--------------------------------------------------------------------------
    */

    form.addEventListener("submit", () => {

        // 検索条件を変更した場合は1ページ目から表示する
        const pageInput = form.querySelector('[name="page"]');

        if (pageInput) {
            pageInput.remove();
        }

        // 通常のGET送信はブラウザに任せる
    });

})();
