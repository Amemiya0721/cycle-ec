/*
|--------------------------------------------------------------------------
| メール送信設定
|--------------------------------------------------------------------------
|
| 管理画面の二段階認証（2FA）で使用する。
|
| 認証フロー：
|   1. メールアドレス・パスワードでログイン
|   2. SMTP経由で6桁の認証コードを送信
|   3. 認証コードを入力
|   4. 認証成功後、管理画面へ遷移
|
| メール送信にはSMTPを使用する。
|
| ※AWS（SES等）は使用しない。
|
| 開発環境：
|   MailHog等のローカルSMTPを使用してメール送信をテストする。
|
| 本番環境：
|   無料または無料枠のあるSMTPサービスを利用する。
|
| 候補：
|   ・Brevo SMTP
|   ・Gmail SMTP
|   ・Outlook SMTP
|
| PHPからのメール送信にはPHPMailerを使用する予定。
|
| SMTPの認証情報はソースコードに直接記述せず、
| 環境変数から取得する。
|
*/